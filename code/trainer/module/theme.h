namespace menyoo_vr {
// Full source theme data, including native GTA font identities. This is not
// permission to substitute an arbitrary desktop font for the original font.
enum ThemeColour { ThemeHeader,ThemeBackground,ThemeTitle,ThemeOption,ThemeSelected,
 ThemeBreak,ThemeCounter,ThemeHighlight,ThemeTrackers,ThemeColourCount };
enum ThemeFlag { Gradient=1u,Rainbow=2u,Separator=4u };
struct ThemeStyle {Colour colour[ThemeColourCount];uint32_t font[6],flags;};
struct NamedTheme {const char*name;ThemeStyle style;};
inline ThemeStyle defaultStyle(){
 ThemeStyle s={};const Colour colours[ThemeColourCount]={{0,255,255,247},{10,10,10,200},
  {255,255,255,255},{255,255,255,255},{0,0,0,255},{255,255,255,240},
  {255,255,255,255},{255,255,255,211},{0,255,255,205}};
 for(unsigned i=0;i<ThemeColourCount;++i)s.colour[i]=colours[i];
 const uint32_t fonts[6]={7,4,4,1,0,0};for(unsigned i=0;i<6;++i)s.font[i]=fonts[i];s.flags=5;return s;
}
}
#include "theme_table.inl" // generated byte-pinned upstream theme catalogue
namespace menyoo_vr {
inline bool validStyle(const ThemeStyle&s){
 if(s.flags&~7u)return false;
 for(unsigned i=0;i<ThemeColourCount;++i){const Colour&c=s.colour[i];if(c.r>255||c.g>255||c.b>255||c.a>255)return false;}
 for(unsigned i=0;i<6;++i)if(s.font[i]>7)return false;
 return true;
}
inline bool sameStyle(const ThemeStyle&a,const ThemeStyle&b){
 if(a.flags!=b.flags)return false;
 for(unsigned i=0;i<ThemeColourCount;++i)if(memcmp(&a.colour[i],&b.colour[i],sizeof(Colour)))return false;
 for(unsigned i=0;i<6;++i)if(a.font[i]!=b.font[i])return false;
 return true;
}
inline bool chooseTheme(unsigned index,Appearance&appearance,ThemeStyle&style){
 if(index>=ThemeCount||!validAppearance(appearance)||!validStyle(OriginalThemes[index].style))return false;
 style=OriginalThemes[index].style;
 // User explicitly requests transparency even when an upstream palette is
 // opaque. Keep all native RGB/font/navigation identities; cap only panel alpha.
 if(style.colour[ThemeBackground].a>200)style.colour[ThemeBackground].a=200;
 if(style.colour[ThemeHeader].a>247)style.colour[ThemeHeader].a=247;
 appearance.colour[Header]=style.colour[ThemeHeader];appearance.colour[Background]=style.colour[ThemeBackground];
 appearance.colour[TitleText]=style.colour[ThemeTitle];appearance.colour[OptionText]=style.colour[ThemeOption];
 appearance.colour[SelectedText]=style.colour[ThemeSelected];appearance.colour[Selection]=style.colour[ThemeHighlight];
 appearance.colour[HelpText]=style.colour[ThemeOption];return true;
}
}

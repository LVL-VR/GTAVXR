inline unsigned vrFormatCount()
{
    return sizeof(VrFormats) / sizeof(VrFormats[0]);
}
inline const char* vrFormat(const char* source, uint32_t language, bool* known = NULL)
{
    if (!source)
        return "";
    for (unsigned i = 0; i < vrFormatCount(); ++i)
    {
        const VrFormatText& entry = VrFormats[i];
        if (!strcmp(source, entry.source))
        {
            if (known)
                *known = true;
            return language == 1 ? entry.spanish : entry.english;
        }
    }
    if (known)
        *known = false;
    return source;
}
